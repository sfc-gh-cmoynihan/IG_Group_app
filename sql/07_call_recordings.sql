USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS CUSTOMER_CALLS;
CREATE SCHEMA IF NOT EXISTS CUSTOMER_CALLS.RECORDINGS;
CREATE STAGE IF NOT EXISTS CUSTOMER_CALLS.RECORDINGS.CALL_RECORDINGS
  DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  COMMENT = 'Synthetic IG phone call recordings (MP4/AAC, TTS from CUSTOMER_CONTACTS.TRANSCRIPT)';
PUT file:///tmp/calls_mp4/*.mp4 @CUSTOMER_CALLS.RECORDINGS.CALL_RECORDINGS AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
ALTER STAGE CUSTOMER_CALLS.RECORDINGS.CALL_RECORDINGS REFRESH;
CREATE OR REPLACE VIEW CUSTOMER_CALLS.RECORDINGS.CALL_RECORDING_CATALOG AS
SELECT REPLACE(d.RELATIVE_PATH, '.mp4') AS CONTACT_ID, d.RELATIVE_PATH, d.SIZE, d.LAST_MODIFIED,
       TO_FILE('@CUSTOMER_CALLS.RECORDINGS.CALL_RECORDINGS', d.RELATIVE_PATH) AS RECORDING_FILE,
       c.CLIENT_ID, c.AGENT_ID, c.START_TS, c.REASON, c.FCA_DISCLOSURE_GIVEN, c.TRANSCRIPT
FROM DIRECTORY(@CUSTOMER_CALLS.RECORDINGS.CALL_RECORDINGS) d
JOIN IG_GROUP_DB.STRUCTURED.CUSTOMER_CONTACTS c ON c.CONTACT_ID = REPLACE(d.RELATIVE_PATH, '.mp4');
SELECT COUNT(*) N, SUM(IFF(FCA_DISCLOSURE_GIVEN,0,1)) MISSED_DISCLOSURE FROM CUSTOMER_CALLS.RECORDINGS.CALL_RECORDING_CATALOG;
