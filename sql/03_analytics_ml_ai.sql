CREATE OR REPLACE DYNAMIC TABLE DT_EXPOSURE_BY_INSTRUMENT
  TARGET_LAG = '5 minutes' WAREHOUSE = IG_WH
  COMMENT = 'Net client exposure vs hedge per instrument (market-maker book)'
AS
SELECT i.INSTRUMENT_ID, i.SYMBOL, i.NAME, i.ASSET_CLASS, i.HEDGE_VENUE,
       COUNT(*)                                                     AS OPEN_POSITIONS,
       COUNT(DISTINCT p.CLIENT_ID)                                  AS CLIENTS,
       SUM(IFF(p.DIRECTION = 'LONG',  p.NOTIONAL_GBP, 0))           AS CLIENT_LONG_GBP,
       SUM(IFF(p.DIRECTION = 'SHORT', p.NOTIONAL_GBP, 0))           AS CLIENT_SHORT_GBP,
       SUM(IFF(p.DIRECTION = 'LONG', p.NOTIONAL_GBP, -p.NOTIONAL_GBP)) AS NET_CLIENT_GBP,
       SUM(p.MARGIN_GBP)                                            AS MARGIN_GBP,
       SUM(p.UNREALISED_PNL_GBP)                                    AS CLIENT_UNREALISED_PNL_GBP,
       ANY_VALUE(h.HEDGE_NOTIONAL_GBP)                              AS HEDGE_GBP,
       SUM(IFF(p.DIRECTION = 'LONG', p.NOTIONAL_GBP, -p.NOTIONAL_GBP)) + COALESCE(ANY_VALUE(h.HEDGE_NOTIONAL_GBP), 0) AS RESIDUAL_HOUSE_EXPOSURE_GBP,
       ANY_VALUE(h.PRIME_BROKER)                                    AS PRIME_BROKER,
       ANY_VALUE(h.HEDGE_COST_BPS)                                  AS HEDGE_COST_BPS
FROM POSITIONS p
JOIN INSTRUMENTS i ON i.INSTRUMENT_ID = p.INSTRUMENT_ID
LEFT JOIN HEDGE_POSITIONS h ON h.INSTRUMENT_ID = p.INSTRUMENT_ID
WHERE p.PRODUCT_LINE IN ('CFD','SPREAD_BET','PRIME','CRYPTO')
GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE DT_CLIENT_MARGIN_RISK
  TARGET_LAG = '5 minutes' WAREHOUSE = IG_WH
  COMMENT = 'Per-account margin utilisation and close-out proximity'
AS
SELECT b.ACCOUNT_ID, b.CLIENT_ID, c.FULL_NAME, c.ENTITY, c.SEGMENT, b.PRODUCT_LINE,
       b.CASH_BALANCE_GBP, b.MARGIN_USED_GBP, b.UNREALISED_PNL_GBP,
       b.CASH_BALANCE_GBP + b.UNREALISED_PNL_GBP AS EQUITY_GBP,
       DIV0NULL(b.CASH_BALANCE_GBP + b.UNREALISED_PNL_GBP, b.MARGIN_USED_GBP) * 100 AS MARGIN_LEVEL_PCT,
       CASE WHEN b.MARGIN_USED_GBP = 0 THEN 'No positions'
            WHEN DIV0NULL(b.CASH_BALANCE_GBP + b.UNREALISED_PNL_GBP, b.MARGIN_USED_GBP) < 0.5 THEN 'Close-out'
            WHEN DIV0NULL(b.CASH_BALANCE_GBP + b.UNREALISED_PNL_GBP, b.MARGIN_USED_GBP) < 1.0 THEN 'Margin call'
            WHEN DIV0NULL(b.CASH_BALANCE_GBP + b.UNREALISED_PNL_GBP, b.MARGIN_USED_GBP) < 1.5 THEN 'Watch'
            ELSE 'Healthy' END AS MARGIN_STATUS
FROM ACCOUNT_BALANCES b JOIN CLIENTS c USING (CLIENT_ID)
WHERE b.MARGIN_USED_GBP > 0;

-- 1-day historical VaR (99%) per instrument on the residual house book
CREATE OR REPLACE VIEW RISK_VAR_BY_INSTRUMENT AS
WITH q AS (SELECT INSTRUMENT_ID, PERCENTILE_CONT(0.01) WITHIN GROUP (ORDER BY LOG_RETURN) AS P01,
                  PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY LOG_RETURN) AS P99, STDDEV(LOG_RETURN) AS VOL
           FROM MARKET_PRICES GROUP BY 1)
SELECT e.INSTRUMENT_ID, e.SYMBOL, e.ASSET_CLASS, e.RESIDUAL_HOUSE_EXPOSURE_GBP, q.VOL AS DAILY_VOL,
       ROUND(ABS(e.RESIDUAL_HOUSE_EXPOSURE_GBP) * IFF(e.RESIDUAL_HOUSE_EXPOSURE_GBP >= 0, -q.P01, q.P99), 2) AS VAR_99_1D_GBP
FROM DT_EXPOSURE_BY_INSTRUMENT e JOIN q USING (INSTRUMENT_ID);

CREATE OR REPLACE TABLE STRESS_SCENARIOS (SCENARIO STRING, ASSET_CLASS STRING, SHOCK_PCT FLOAT) AS
SELECT * FROM VALUES
 ('Equity crash -10%','Index',-0.10),('Equity crash -10%','Share',-0.12),('Equity crash -10%','Crypto',-0.20),
 ('USD spike +5%','FX',0.05),('USD spike +5%','Commodity',-0.04),
 ('Crypto winter -35%','Crypto',-0.35),
 ('Oil shock +25%','Commodity',0.25),
 ('Rates shock +100bp','Bond',-0.06),('Rates shock +100bp','Index',-0.04);

CREATE OR REPLACE VIEW RISK_STRESS_RESULTS AS
SELECT s.SCENARIO, e.ASSET_CLASS, SUM(e.RESIDUAL_HOUSE_EXPOSURE_GBP * s.SHOCK_PCT) AS HOUSE_PNL_GBP,
       SUM(e.NET_CLIENT_GBP * s.SHOCK_PCT) AS CLIENT_PNL_GBP
FROM DT_EXPOSURE_BY_INSTRUMENT e JOIN STRESS_SCENARIOS s USING (ASSET_CLASS)
GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE DT_DAILY_REVENUE
  TARGET_LAG = '1 hour' WAREHOUSE = IG_WH
  COMMENT = 'Daily revenue by entity and product line'
AS
SELECT TRADE_TS::DATE AS TRADE_DATE, ENTITY, PRODUCT_LINE,
       COUNT(*) AS TRADES, COUNT(DISTINCT CLIENT_ID) AS ACTIVE_CLIENTS,
       SUM(NOTIONAL_GBP) AS NOTIONAL_GBP, SUM(SPREAD_REVENUE_GBP) AS SPREAD_REVENUE_GBP,
       SUM(COMMISSION_GBP) AS COMMISSION_GBP, SUM(FINANCING_GBP) AS FINANCING_GBP,
       SUM(SPREAD_REVENUE_GBP + COMMISSION_GBP + FINANCING_GBP) AS TOTAL_REVENUE_GBP,
       SUM(CLIENT_PNL_GBP) AS CLIENT_PNL_GBP
FROM TRADES GROUP BY ALL;

