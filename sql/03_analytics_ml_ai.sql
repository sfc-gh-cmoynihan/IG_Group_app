    'Client ' || CLIENT_ID || ' (' || ENTITY || ', ' || COUNTRY || '). Rules hit: ' || REASONS || '. ' ||
    'Last 30d: ' || N_PAY_30D || ' payments, deposits GBP ' || ROUND(DEP_GBP) || ', withdrawals GBP ' || ROUND(WD_GBP) || ', ' ||
    PAYER_COUNTRIES || ' payer countries, ' || TRADES_30D || ' trades. Last 7d: ' || FAILED_7D || ' failed logins, ' ||
    IP_COUNTRIES_7D || ' IP countries, ' || DEVICES_7D || ' devices. Risk score ' || RISK_SCORE || '.') AS S
  FROM FRAUD_ALERTS QUALIFY ROW_NUMBER() OVER (ORDER BY RISK_SCORE DESC) <= 40) x
WHERE f.ALERT_ID = x.ALERT_ID;

