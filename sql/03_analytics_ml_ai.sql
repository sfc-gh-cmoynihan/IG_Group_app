CREATE OR REPLACE DYNAMIC TABLE DT_CLIENT_360
  TARGET_LAG = '1 hour' WAREHOUSE = IG_WH
  COMMENT = 'Single governed client view: onboarding, trading, money, CRM, support'
AS
WITH tr AS (SELECT CLIENT_ID, COUNT(*) TRADES_180D, SUM(NOTIONAL_GBP) NOTIONAL_180D,
                   SUM(SPREAD_REVENUE_GBP + COMMISSION_GBP + FINANCING_GBP) REVENUE_180D,
                   SUM(CLIENT_PNL_GBP) CLIENT_PNL_180D, MAX(TRADE_TS) LAST_TRADE_TS,
                   COUNT_IF(TRADE_TS >= DATEADD(day, -30, CURRENT_DATE())) TRADES_30D,
                   COUNT(DISTINCT PRODUCT_LINE) PRODUCTS_TRADED,
                   MODE(CHANNEL) PREFERRED_CHANNEL
            FROM TRADES GROUP BY 1),
pay AS (SELECT CLIENT_ID, SUM(IFF(DIRECTION = 'DEPOSIT', AMOUNT_GBP, 0)) DEPOSITS_GBP,
               SUM(IFF(DIRECTION = 'WITHDRAWAL', AMOUNT_GBP, 0)) WITHDRAWALS_GBP FROM PAYMENTS WHERE STATUS = 'Settled' GROUP BY 1),
bal AS (SELECT CLIENT_ID, SUM(CASH_BALANCE_GBP) BALANCE_GBP, COUNT(*) ACCOUNTS FROM ACCOUNT_BALANCES GROUP BY 1),
sup AS (SELECT CLIENT_ID, COUNT(*) SUPPORT_CONTACTS FROM IG_GROUP_DB.UNSTRUCTURED.SUPPORT_CHATS GROUP BY 1),
cmp AS (SELECT CLIENT_ID, COUNT(*) COMPLAINTS, COUNT_IF(STATUS = 'Open') OPEN_COMPLAINTS FROM IG_GROUP_DB.UNSTRUCTURED.COMPLAINTS GROUP BY 1)
SELECT c.CLIENT_ID, c.FULL_NAME, c.EMAIL, c.ENTITY, c.COUNTRY, c.SEGMENT, c.ACQUISITION_CHANNEL, c.AGE_BAND,
       c.PRIMARY_PRODUCT, c.SIGNUP_DATE, c.FIRST_FUNDED_DATE, c.FIRST_TRADE_DATE, c.KYC_STATUS,
       crm.PROFILE:tier::STRING AS CRM_TIER, crm.PROFILE:owner::STRING AS CRM_OWNER,
       crm.PROFILE:marketing.email_opt_in::BOOLEAN AS EMAIL_OPT_IN, crm.PROFILE:nps::INT AS NPS,
       COALESCE(bal.ACCOUNTS, 0) ACCOUNTS, COALESCE(bal.BALANCE_GBP, 0) BALANCE_GBP,
       COALESCE(pay.DEPOSITS_GBP, 0) DEPOSITS_GBP, COALESCE(pay.WITHDRAWALS_GBP, 0) WITHDRAWALS_GBP,
       COALESCE(tr.TRADES_180D, 0) TRADES_180D, COALESCE(tr.TRADES_30D, 0) TRADES_30D,
       COALESCE(tr.NOTIONAL_180D, 0) NOTIONAL_180D, COALESCE(tr.REVENUE_180D, 0) REVENUE_180D,
       COALESCE(tr.CLIENT_PNL_180D, 0) CLIENT_PNL_180D, tr.LAST_TRADE_TS, COALESCE(tr.PRODUCTS_TRADED, 0) PRODUCTS_TRADED,
       tr.PREFERRED_CHANNEL,
       COALESCE(sup.SUPPORT_CONTACTS, 0) SUPPORT_CONTACTS, COALESCE(cmp.COMPLAINTS, 0) COMPLAINTS,
       COALESCE(cmp.OPEN_COMPLAINTS, 0) OPEN_COMPLAINTS,
       CASE WHEN c.FIRST_FUNDED_DATE IS NULL THEN 'Registered'
            WHEN c.FIRST_TRADE_DATE IS NULL THEN 'Funded'
            WHEN tr.LAST_TRADE_TS >= DATEADD(day, -30, CURRENT_DATE()) THEN 'Active'
            WHEN tr.LAST_TRADE_TS >= DATEADD(day, -90, CURRENT_DATE()) THEN 'Lapsing'
            ELSE 'Dormant' END AS LIFECYCLE_STAGE
FROM CLIENTS c
LEFT JOIN IG_GROUP_DB.SEMI_STRUCTURED.CRM_PROFILES crm USING (CLIENT_ID)
LEFT JOIN tr USING (CLIENT_ID) LEFT JOIN pay USING (CLIENT_ID) LEFT JOIN bal USING (CLIENT_ID)
LEFT JOIN sup USING (CLIENT_ID) LEFT JOIN cmp USING (CLIENT_ID);

-- ------------------------------------------------------------------ --
-- UC1  Churn model (Snowflake ML Classification, in-database)
--   Label: traded clients with no trade in last 45 days.
--   Features avoid recency (no leakage of the label definition).
-- ------------------------------------------------------------------ --
CREATE OR REPLACE VIEW CHURN_FEATURES AS
SELECT c.CLIENT_ID, c.ENTITY, c.SEGMENT, c.ACQUISITION_CHANNEL, c.AGE_BAND, c.PRIMARY_PRODUCT, c.CRM_TIER,
       DATEDIFF(day, c.SIGNUP_DATE, CURRENT_DATE())     AS TENURE_DAYS,
       DATEDIFF(day, c.SIGNUP_DATE, c.FIRST_FUNDED_DATE) AS DAYS_TO_FUND,
       c.ACCOUNTS, c.PRODUCTS_TRADED, LN(1 + c.DEPOSITS_GBP) AS LOG_DEPOSITS,
       DIV0NULL(c.WITHDRAWALS_GBP, c.DEPOSITS_GBP)       AS WITHDRAWAL_RATIO,
       DIV0NULL(c.CLIENT_PNL_180D, c.NOTIONAL_180D) * 100 AS PNL_PCT_OF_NOTIONAL,
       c.SUPPORT_CONTACTS, c.COMPLAINTS, COALESCE(c.NPS, -1) AS NPS,
       IFF(c.LAST_TRADE_TS < DATEADD(day, -45, CURRENT_DATE()), 1, 0) AS CHURNED
FROM DT_CLIENT_360 c
WHERE c.FIRST_TRADE_DATE IS NOT NULL AND c.FIRST_TRADE_DATE < DATEADD(day, -60, CURRENT_DATE());

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION IG_CHURN_MODEL(
  INPUT_DATA => SYSTEM$QUERY_REFERENCE('SELECT * EXCLUDE (CLIENT_ID) FROM IG_GROUP_DB.STRUCTURED.CHURN_FEATURES SAMPLE (250000 ROWS)'),
  TARGET_COLNAME => 'CHURNED',
  CONFIG_OBJECT => {'evaluate': TRUE, 'on_error': 'skip'});

-- Score currently-active clients (risk of leaving) + next-best-action
CREATE OR REPLACE TABLE CHURN_SCORES AS
WITH f AS (
  SELECT c.CLIENT_ID, c.ENTITY, c.SEGMENT, c.ACQUISITION_CHANNEL, c.AGE_BAND, c.PRIMARY_PRODUCT, c.CRM_TIER,
         DATEDIFF(day, c.SIGNUP_DATE, CURRENT_DATE()) TENURE_DAYS, DATEDIFF(day, c.SIGNUP_DATE, c.FIRST_FUNDED_DATE) DAYS_TO_FUND,
         c.ACCOUNTS, c.PRODUCTS_TRADED, LN(1 + c.DEPOSITS_GBP) LOG_DEPOSITS, DIV0NULL(c.WITHDRAWALS_GBP, c.DEPOSITS_GBP) WITHDRAWAL_RATIO,
         DIV0NULL(c.CLIENT_PNL_180D, c.NOTIONAL_180D) * 100 PNL_PCT_OF_NOTIONAL,
         c.SUPPORT_CONTACTS, c.COMPLAINTS, COALESCE(c.NPS, -1) NPS,
         c.REVENUE_180D, c.PRIMARY_PRODUCT AS PP, c.EMAIL_OPT_IN
  FROM DT_CLIENT_360 c WHERE c.LIFECYCLE_STAGE IN ('Active','Lapsing')),
p AS (
  SELECT f.CLIENT_ID, f.REVENUE_180D, f.PP, f.PRODUCTS_TRADED, f.COMPLAINTS, f.EMAIL_OPT_IN, f.PNL_PCT_OF_NOTIONAL,
         IG_CHURN_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT_KEEP_NULL(
           'ENTITY', f.ENTITY, 'SEGMENT', f.SEGMENT, 'ACQUISITION_CHANNEL', f.ACQUISITION_CHANNEL, 'AGE_BAND', f.AGE_BAND,
           'PRIMARY_PRODUCT', f.PRIMARY_PRODUCT, 'CRM_TIER', f.CRM_TIER, 'TENURE_DAYS', f.TENURE_DAYS, 'DAYS_TO_FUND', f.DAYS_TO_FUND,
           'ACCOUNTS', f.ACCOUNTS, 'PRODUCTS_TRADED', f.PRODUCTS_TRADED, 'LOG_DEPOSITS', f.LOG_DEPOSITS,
           'WITHDRAWAL_RATIO', f.WITHDRAWAL_RATIO, 'PNL_PCT_OF_NOTIONAL', f.PNL_PCT_OF_NOTIONAL,
           'SUPPORT_CONTACTS', f.SUPPORT_CONTACTS, 'COMPLAINTS', f.COMPLAINTS, 'NPS', f.NPS)) AS PRED
  FROM f)
SELECT CLIENT_ID,
       ROUND(PRED:probability:"1"::FLOAT, 4) AS CHURN_PROBABILITY,
       CASE WHEN PRED:probability:"1"::FLOAT >= 0.6 THEN 'High' WHEN PRED:probability:"1"::FLOAT >= 0.35 THEN 'Medium' ELSE 'Low' END AS CHURN_RISK,
       ROUND(REVENUE_180D * PRED:probability:"1"::FLOAT, 2) AS REVENUE_AT_RISK_GBP,
       CASE WHEN COMPLAINTS > 0 AND PRED:probability:"1"::FLOAT >= 0.35 THEN 'Service recovery call from senior agent'
            WHEN PNL_PCT_OF_NOTIONAL < -1.5 THEN 'Risk-management education + guaranteed stops prompt'
            WHEN PP IN ('CFD','SPREAD_BET') AND PRODUCTS_TRADED = 1 THEN 'Cross-sell Share Dealing / ISA'
            WHEN PP = 'SHARE_DEALING' THEN 'Offer Smart Portfolio or ISA transfer'
            WHEN PP = 'OPTIONS_FUTURES' THEN 'tastytrade options education webinar'
            ELSE 'Personalised market insight email' END AS NEXT_BEST_ACTION,
       CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS SCORED_TS
FROM p;

-- Model introspection (SHOW_*_METRICS / SHOW_FEATURE_IMPORTANCE) errors on this account,
-- so compute evaluation metrics directly from labelled predictions.
CREATE OR REPLACE TABLE CHURN_MODEL_METRICS AS
WITH s AS (
  SELECT CHURNED, IG_CHURN_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT_KEEP_NULL(
           'ENTITY', ENTITY, 'SEGMENT', SEGMENT, 'ACQUISITION_CHANNEL', ACQUISITION_CHANNEL, 'AGE_BAND', AGE_BAND,
           'PRIMARY_PRODUCT', PRIMARY_PRODUCT, 'CRM_TIER', CRM_TIER, 'TENURE_DAYS', TENURE_DAYS, 'DAYS_TO_FUND', DAYS_TO_FUND,
           'ACCOUNTS', ACCOUNTS, 'PRODUCTS_TRADED', PRODUCTS_TRADED, 'LOG_DEPOSITS', LOG_DEPOSITS,
           'WITHDRAWAL_RATIO', WITHDRAWAL_RATIO, 'PNL_PCT_OF_NOTIONAL', PNL_PCT_OF_NOTIONAL,
           'SUPPORT_CONTACTS', SUPPORT_CONTACTS, 'COMPLAINTS', COMPLAINTS, 'NPS', NPS)):class::INT AS PRED
  FROM CHURN_FEATURES SAMPLE (100000 ROWS))
SELECT COUNT(*) AS N, AVG(CHURNED) AS BASE_RATE,
       DIV0NULL(COUNT_IF(PRED = 1 AND CHURNED = 1), COUNT_IF(PRED = 1)) AS PRECISION,
       DIV0NULL(COUNT_IF(PRED = 1 AND CHURNED = 1), COUNT_IF(CHURNED = 1)) AS RECALL,
       DIV0NULL(COUNT_IF(PRED = CHURNED), COUNT(*)) AS ACCURACY
FROM s;

-- Churn rate by driver (explainability for the UI)
CREATE OR REPLACE VIEW CHURN_DRIVERS AS
SELECT 'Acquisition channel' AS DRIVER, ACQUISITION_CHANNEL AS VALUE, COUNT(*) CLIENTS, AVG(CHURNED) CHURN_RATE FROM CHURN_FEATURES GROUP BY 1, 2
UNION ALL SELECT 'Age band', AGE_BAND, COUNT(*), AVG(CHURNED) FROM CHURN_FEATURES GROUP BY 1, 2
UNION ALL SELECT 'Segment', SEGMENT, COUNT(*), AVG(CHURNED) FROM CHURN_FEATURES GROUP BY 1, 2
UNION ALL SELECT 'Primary product', PRIMARY_PRODUCT, COUNT(*), AVG(CHURNED) FROM CHURN_FEATURES GROUP BY 1, 2
UNION ALL SELECT 'Has complained', IFF(COMPLAINTS > 0, 'Yes', 'No'), COUNT(*), AVG(CHURNED) FROM CHURN_FEATURES GROUP BY 1, 2;

-- Marketing segment for activation (shared via secure view / share)
CREATE OR REPLACE SECURE VIEW MARKETING_SEGMENTS AS
SELECT c.CLIENT_ID, SHA2(LOWER(c.EMAIL)) AS EMAIL_SHA256, c.ENTITY, c.COUNTRY, c.SEGMENT, c.PRIMARY_PRODUCT,
       s.CHURN_RISK, s.NEXT_BEST_ACTION,
       CASE WHEN s.CHURN_RISK = 'High' THEN 'Retention - high risk'
            WHEN c.LIFECYCLE_STAGE = 'Funded' THEN 'Activation - funded not traded'
            WHEN c.LIFECYCLE_STAGE = 'Registered' THEN 'Conversion - registered not funded'
            WHEN c.LIFECYCLE_STAGE = 'Dormant' THEN 'Win-back - dormant'
            ELSE 'Growth - cross-sell' END AS AUDIENCE
FROM DT_CLIENT_360 c LEFT JOIN CHURN_SCORES s USING (CLIENT_ID)
WHERE c.EMAIL_OPT_IN;

