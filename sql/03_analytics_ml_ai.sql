CREATE OR REPLACE VIEW REG_REPORTING_SUMMARY AS
SELECT ENTITY, REGIME, REGULATOR, SUBMITTED_TS::DATE AS REPORT_DATE,
       COUNT(*) AS REPORTS, COUNT_IF(STATUS = 'ACCEPTED') AS ACCEPTED, COUNT_IF(STATUS = 'REJECTED') AS REJECTED,
       COUNT_IF(STATUS = 'LATE') AS LATE, COUNT_IF(STATUS = 'PENDING') AS PENDING,
       ROUND(100 * COUNT_IF(STATUS = 'ACCEPTED') / COUNT(*), 2) AS ACCEPTANCE_RATE_PCT,
       ROUND(AVG(DATEDIFF(minute, TRADE_TS, SUBMITTED_TS)) / 60, 2) AS AVG_SUBMISSION_HOURS
FROM REG_TRANSACTION_REPORTS GROUP BY ALL;

CREATE OR REPLACE VIEW CONSUMER_DUTY_OUTCOMES AS
SELECT c.ENTITY, c.SEGMENT, c.PRIMARY_PRODUCT,
       COUNT(*) AS CLIENTS,
       ROUND(100 * COUNT_IF(c.CLIENT_PNL_180D < 0) / NULLIF(COUNT_IF(c.TRADES_180D > 0), 0), 1) AS PCT_LOSING_CLIENTS,
       ROUND(AVG(c.REVENUE_180D), 2) AS AVG_COST_TO_CLIENT_GBP,
       ROUND(1000 * SUM(c.COMPLAINTS) / NULLIF(COUNT(*), 0), 1) AS COMPLAINTS_PER_1000,
       ROUND(AVG(c.NPS), 1) AS AVG_NPS
FROM DT_CLIENT_360 c GROUP BY ALL;

-- ------------------------------------------------------------------ --
-- UC4  Fraud / AML surveillance
-- ------------------------------------------------------------------ --
CREATE OR REPLACE TABLE FRAUD_ALERTS AS
WITH pay AS (
  SELECT p.CLIENT_ID, COUNT(*) N_PAY_30D,
         COUNT_IF(p.DIRECTION = 'DEPOSIT') DEP, COUNT_IF(p.DIRECTION = 'WITHDRAWAL') WD,
         SUM(IFF(p.DIRECTION = 'DEPOSIT', p.AMOUNT_GBP, 0)) DEP_GBP, SUM(IFF(p.DIRECTION = 'WITHDRAWAL', p.AMOUNT_GBP, 0)) WD_GBP,
         COUNT(DISTINCT p.PAYER_COUNTRY) PAYER_COUNTRIES,
         COUNT_IF(p.PAYER_COUNTRY <> c.COUNTRY) FOREIGN_PAYMENTS
  FROM PAYMENTS p JOIN CLIENTS c USING (CLIENT_ID)
  WHERE p.PAYMENT_TS >= DATEADD(day, -30, CURRENT_DATE()) GROUP BY 1),
lg AS (
  SELECT l.CLIENT_ID, COUNT(*) LOGINS_7D, COUNT_IF(NOT l.SUCCESS) FAILED_7D,
         COUNT(DISTINCT l.IP_COUNTRY) IP_COUNTRIES_7D, COUNT(DISTINCT l.DEVICE_ID) DEVICES_7D,
         COUNT_IF(l.IP_COUNTRY <> c.COUNTRY) FOREIGN_LOGINS_7D
  FROM LOGIN_EVENTS l JOIN CLIENTS c USING (CLIENT_ID)
  WHERE l.LOGIN_TS >= DATEADD(day, -7, CURRENT_DATE()) GROUP BY 1),
tr AS (SELECT CLIENT_ID, COUNT(*) TRADES_30D FROM TRADES WHERE TRADE_TS >= DATEADD(day, -30, CURRENT_DATE()) GROUP BY 1),
sc AS (
  SELECT c.CLIENT_ID, c.FULL_NAME, c.ENTITY, c.COUNTRY,
         COALESCE(pay.N_PAY_30D, 0) N_PAY_30D, COALESCE(pay.DEP_GBP, 0) DEP_GBP, COALESCE(pay.WD_GBP, 0) WD_GBP,
         COALESCE(pay.PAYER_COUNTRIES, 0) PAYER_COUNTRIES, COALESCE(pay.FOREIGN_PAYMENTS, 0) FOREIGN_PAYMENTS,
         COALESCE(lg.FAILED_7D, 0) FAILED_7D, COALESCE(lg.IP_COUNTRIES_7D, 0) IP_COUNTRIES_7D,
         COALESCE(lg.DEVICES_7D, 0) DEVICES_7D, COALESCE(lg.FOREIGN_LOGINS_7D, 0) FOREIGN_LOGINS_7D,
         COALESCE(tr.TRADES_30D, 0) TRADES_30D,
         -- rule hits
         IFF(pay.DEP >= 4 AND pay.WD >= 4 AND COALESCE(tr.TRADES_30D, 0) < 5, 1, 0)        AS R_RAPID_IN_OUT,
         IFF(pay.FOREIGN_PAYMENTS >= 3 AND pay.PAYER_COUNTRIES >= 3, 1, 0)              AS R_MULTI_COUNTRY_CARDS,
         IFF(lg.FOREIGN_LOGINS_7D >= 3 AND lg.FAILED_7D >= 2, 1, 0)                     AS R_ATO_LOGIN_PATTERN,
         IFF(lg.DEVICES_7D >= 4, 1, 0)                                                   AS R_DEVICE_HOPPING,
         IFF(pay.WD_GBP > 0.9 * pay.DEP_GBP AND pay.DEP_GBP > 15000 AND COALESCE(tr.TRADES_30D, 0) < 5, 1, 0) AS R_PASS_THROUGH
  FROM CLIENTS c LEFT JOIN pay USING (CLIENT_ID) LEFT JOIN lg USING (CLIENT_ID) LEFT JOIN tr USING (CLIENT_ID))
SELECT 'ALR' || LPAD(ROW_NUMBER() OVER (ORDER BY CLIENT_ID), 6, '0') AS ALERT_ID, sc.*,
       R_RAPID_IN_OUT * 30 + R_MULTI_COUNTRY_CARDS * 25 + R_ATO_LOGIN_PATTERN * 30 + R_DEVICE_HOPPING * 10 + R_PASS_THROUGH * 25
         + LEAST(FAILED_7D, 10) + LEAST(FOREIGN_PAYMENTS, 10) AS RISK_SCORE,
       ARRAY_TO_STRING(ARRAY_COMPACT(ARRAY_CONSTRUCT(
         IFF(R_RAPID_IN_OUT = 1, 'Rapid deposit/withdrawal cycling', NULL),
         IFF(R_MULTI_COUNTRY_CARDS = 1, 'Cards from multiple foreign countries', NULL),
         IFF(R_ATO_LOGIN_PATTERN = 1, 'Foreign logins with failures (possible account takeover)', NULL),
         IFF(R_DEVICE_HOPPING = 1, 'Many new devices', NULL),
         IFF(R_PASS_THROUGH = 1, 'Funds passed through with minimal trading', NULL))), '; ') AS REASONS,
       CASE WHEN R_RAPID_IN_OUT + R_MULTI_COUNTRY_CARDS + R_PASS_THROUGH >= 1 THEN 'Money mule / AML'
            WHEN R_ATO_LOGIN_PATTERN = 1 THEN 'Account takeover'
            ELSE 'Device anomaly' END AS TYPOLOGY,
       'Open' AS CASE_STATUS, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS CREATED_TS
FROM sc
WHERE R_RAPID_IN_OUT + R_MULTI_COUNTRY_CARDS + R_ATO_LOGIN_PATTERN + R_DEVICE_HOPPING + R_PASS_THROUGH > 0;

