USE SCHEMA IG_GROUP_DB.UNSTRUCTURED;
CREATE OR REPLACE TABLE CHAT_INSIGHTS AS
SELECT CHAT_ID, CLIENT_ID, ENTITY, CHAT_TS, CHANNEL,
       AI_CLASSIFY(TRANSCRIPT, ['Margin and liquidation','Payments and withdrawals','Platform and technology',
                                'Pricing, spreads and fees','Onboarding and verification','Product questions',
                                'Security and fraud','Account closure','Positive feedback'],
                   {'task_description': 'Classify the main topic of this IG Group trading-platform support conversation'}):labels[0]::STRING AS TOPIC,
       AI_CLASSIFY(TRANSCRIPT, ['Intends to leave','Formal complaint','Resolved question','Praise'],
                   {'task_description': 'What is the client outcome or intent at the end of the conversation?'}):labels[0]::STRING AS CLIENT_INTENT,
       AI_SENTIMENT(TRANSCRIPT, ['platform','fees','withdrawals','customer service']) AS SENTIMENT_RAW,
       TRANSCRIPT
FROM SUPPORT_CHATS;

CREATE OR REPLACE VIEW CHAT_INSIGHTS_V AS
SELECT CHAT_ID, CLIENT_ID, ENTITY, CHAT_TS, CHANNEL, TOPIC, CLIENT_INTENT,
       SENTIMENT_RAW:categories[0]:sentiment::STRING AS OVERALL_SENTIMENT,
       MAX(IFF(s.VALUE:name::STRING = 'platform', s.VALUE:sentiment::STRING, NULL)) AS PLATFORM_SENTIMENT,
       MAX(IFF(s.VALUE:name::STRING = 'fees', s.VALUE:sentiment::STRING, NULL)) AS FEES_SENTIMENT,
       MAX(IFF(s.VALUE:name::STRING = 'withdrawals', s.VALUE:sentiment::STRING, NULL)) AS WITHDRAWALS_SENTIMENT,
       MAX(IFF(s.VALUE:name::STRING = 'customer service', s.VALUE:sentiment::STRING, NULL)) AS SERVICE_SENTIMENT,
       TRANSCRIPT
FROM CHAT_INSIGHTS, LATERAL FLATTEN(SENTIMENT_RAW:categories) s
GROUP BY ALL;

