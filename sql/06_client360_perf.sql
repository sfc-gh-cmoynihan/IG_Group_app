-- 06_client360_perf.sql — pre-aggregated Client 360 summaries (per entity) for fast page loads
-- v1.0 2026-11-09
-- The API sums across entities for the "All" view, so every table is grouped by ENTITY.

USE DATABASE IG_GROUP_DB;
USE SCHEMA STRUCTURED;

CREATE OR REPLACE DYNAMIC TABLE C360_KPI_BY_ENTITY TARGET_LAG = '1 hour' WAREHOUSE = IG_WH AS
SELECT c.ENTITY,
       COUNT(*) AS REGISTERED,
       COUNT(c.FIRST_FUNDED_DATE) AS FUNDED,
       COUNT(c.FIRST_TRADE_DATE) AS TRADED,
       COUNT_IF(c.LIFECYCLE_STAGE = 'Active') AS ACTIVE,
       SUM(c.BALANCE_GBP) AS BALANCES,
       SUM(c.DEPOSITS_GBP) - SUM(c.WITHDRAWALS_GBP) AS NET_DEPOSITS,
       SUM(s.REVENUE_AT_RISK_GBP) AS REVENUE_AT_RISK
FROM DT_CLIENT_360 c LEFT JOIN CHURN_SCORES s USING (CLIENT_ID)
GROUP BY 1;

CREATE OR REPLACE DYNAMIC TABLE C360_LIFECYCLE_BY_ENTITY TARGET_LAG = '1 hour' WAREHOUSE = IG_WH AS
SELECT ENTITY, LIFECYCLE_STAGE, COUNT(*) AS N FROM DT_CLIENT_360 GROUP BY 1, 2;

CREATE OR REPLACE DYNAMIC TABLE C360_CHURN_BY_CHANNEL TARGET_LAG = '1 hour' WAREHOUSE = IG_WH AS
SELECT c.ENTITY, c.ACQUISITION_CHANNEL, COUNT(*) AS CLIENTS,
       SUM(s.CHURN_PROBABILITY) AS SUM_CHURN_PROB, SUM(s.REVENUE_AT_RISK_GBP) AS REVENUE_AT_RISK
FROM CHURN_SCORES s JOIN DT_CLIENT_360 c USING (CLIENT_ID)
GROUP BY 1, 2;

-- Top 25 per entity; the global top 25 is always contained in this set.
CREATE OR REPLACE DYNAMIC TABLE C360_AT_RISK_TOP TARGET_LAG = '1 hour' WAREHOUSE = IG_WH AS
SELECT s.CLIENT_ID, c.FULL_NAME, c.ENTITY, c.SEGMENT, c.PRIMARY_PRODUCT, c.ACQUISITION_CHANNEL, c.LIFECYCLE_STAGE,
       s.CHURN_PROBABILITY, s.REVENUE_AT_RISK_GBP, c.REVENUE_180D, c.COMPLAINTS, s.NEXT_BEST_ACTION
FROM CHURN_SCORES s JOIN DT_CLIENT_360 c USING (CLIENT_ID)
WHERE s.CHURN_RISK IN ('High', 'Medium')
QUALIFY ROW_NUMBER() OVER (PARTITION BY c.ENTITY ORDER BY s.REVENUE_AT_RISK_GBP DESC) <= 25;

CREATE OR REPLACE DYNAMIC TABLE C360_CHAT_TOPICS TARGET_LAG = '1 hour' WAREHOUSE = IG_WH AS
SELECT ENTITY, TOPIC, COUNT(*) AS N,
       COUNT_IF(OVERALL_SENTIMENT = 'negative') AS NEGATIVE,
       COUNT_IF(CLIENT_INTENT = 'Intends to leave') AS INTENDS_TO_LEAVE
FROM IG_GROUP_DB.UNSTRUCTURED.CHAT_INSIGHTS_V GROUP BY 1, 2;

CREATE OR REPLACE DYNAMIC TABLE C360_SEGMENTS TARGET_LAG = '1 hour' WAREHOUSE = IG_WH AS
SELECT ENTITY, AUDIENCE, COUNT(*) AS CLIENTS FROM DYNAMIC_TABLE_REFRESH_BOUNDARY(MARKETING_SEGMENTS) GROUP BY 1, 2;

-- Point lookups for the single-client drill-down (/api/clients/[id]).
ALTER TABLE TRADES ADD SEARCH OPTIMIZATION ON EQUALITY(CLIENT_ID);
ALTER TABLE ACCOUNTS ADD SEARCH OPTIMIZATION ON EQUALITY(CLIENT_ID);
ALTER TABLE ACCOUNT_BALANCES ADD SEARCH OPTIMIZATION ON EQUALITY(ACCOUNT_ID);
ALTER TABLE CHURN_SCORES ADD SEARCH OPTIMIZATION ON EQUALITY(CLIENT_ID);
ALTER DYNAMIC TABLE DT_CLIENT_360 ADD SEARCH OPTIMIZATION ON EQUALITY(CLIENT_ID);
