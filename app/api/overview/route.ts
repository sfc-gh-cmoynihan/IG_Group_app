import { errorResponse, q } from '@/lib/ig-server';
import { S, U } from '@/lib/constants';

export const dynamic = 'force-dynamic';

export async function GET() {
  try {
    const [kpi, revenue, byProduct, entities] = await Promise.all([
      q(`SELECT
           (SELECT COUNT(*) FROM ${S}.DT_CLIENT_360) AS CLIENTS,
           (SELECT COUNT(FIRST_FUNDED_DATE) FROM ${S}.DT_CLIENT_360) AS FUNDED_CLIENTS,
           (SELECT COUNT_IF(FIRST_FUNDED_DATE IS NOT NULL AND ENTITY = 'Freetrade') FROM ${S}.DT_CLIENT_360) AS FREETRADE_FUNDED,
           (SELECT COUNT_IF(LIFECYCLE_STAGE = 'Active') FROM ${S}.DT_CLIENT_360) AS ACTIVE_CLIENTS,
           (SELECT SUM(TOTAL_REVENUE_GBP) FROM ${S}.DT_DAILY_REVENUE WHERE TRADE_DATE >= DATEADD(day, -30, CURRENT_DATE())) AS REVENUE_30D,
           (SELECT SUM(ABS(RESIDUAL_HOUSE_EXPOSURE_GBP)) FROM ${S}.DT_EXPOSURE_BY_INSTRUMENT) AS GROSS_RESIDUAL_GBP,
           (SELECT SUM(VAR_99_1D_GBP) FROM ${S}.RISK_VAR_BY_INSTRUMENT) AS VAR_GBP,
           (SELECT 100 * COUNT_IF(STATUS = 'ACCEPTED') / COUNT(*) FROM ${S}.REG_TRANSACTION_REPORTS) AS REPORT_ACCEPTANCE_PCT,
           (SELECT COUNT(*) FROM ${S}.FRAUD_ALERTS WHERE CASE_STATUS = 'Open') AS OPEN_ALERTS,
           (SELECT SUM(REVENUE_AT_RISK_GBP) FROM ${S}.CHURN_SCORES) AS REVENUE_AT_RISK,
           (SELECT COUNT(*) FROM ${U}.COMPLAINTS WHERE STATUS = 'Open') AS OPEN_COMPLAINTS`),
      q(`SELECT TO_CHAR(TRADE_DATE, 'YYYY-MM-DD') AS D, SUM(TOTAL_REVENUE_GBP) AS REVENUE, SUM(ACTIVE_CLIENTS) AS TRADERS
         FROM ${S}.DT_DAILY_REVENUE WHERE TRADE_DATE >= DATEADD(day, -90, CURRENT_DATE()) GROUP BY 1 ORDER BY 1`),
      q(`SELECT PRODUCT_LINE, SUM(TOTAL_REVENUE_GBP) AS REVENUE, SUM(TRADES) AS TRADES
         FROM ${S}.DT_DAILY_REVENUE WHERE TRADE_DATE >= DATEADD(day, -30, CURRENT_DATE()) GROUP BY 1 ORDER BY 2 DESC`),
      q(`SELECT e.ENTITY, e.REGULATOR, e.REGION,
                COUNT(c.CLIENT_ID) AS CLIENTS, SUM(c.REVENUE_180D) AS REVENUE_180D, SUM(c.BALANCE_GBP) AS BALANCES
         FROM ${S}.ENTITIES e LEFT JOIN ${S}.DT_CLIENT_360 c ON c.ENTITY = e.ENTITY
         GROUP BY ALL ORDER BY REVENUE_180D DESC`),
    ]);
    return Response.json({ kpi: kpi[0] ?? {}, revenue, byProduct, entities });
  } catch (e) {
    return errorResponse('overview', e);
  }
}
