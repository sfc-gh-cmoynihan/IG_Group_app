import { errorResponse, q } from '@/lib/ig-server';
import { S } from '@/lib/constants';

export const dynamic = 'force-dynamic';

export async function GET() {
  try {
    const [byEntity, daily, rejects, cass, duty, kpi] = await Promise.all([
      q(`SELECT ENTITY, REGIME, REGULATOR, COUNT(*) AS REPORTS,
                COUNT_IF(STATUS = 'ACCEPTED') AS ACCEPTED, COUNT_IF(STATUS = 'REJECTED') AS REJECTED,
                COUNT_IF(STATUS = 'LATE') AS LATE, COUNT_IF(STATUS = 'PENDING') AS PENDING,
                100 * COUNT_IF(STATUS = 'ACCEPTED') / COUNT(*) AS ACCEPTANCE_PCT
         FROM ${S}.REG_TRANSACTION_REPORTS GROUP BY ALL ORDER BY ACCEPTANCE_PCT`),
      q(`SELECT TO_CHAR(REPORT_DATE, 'YYYY-MM-DD') AS D, SUM(REPORTS) AS REPORTS, SUM(REJECTED) AS REJECTED, SUM(LATE) AS LATE
         FROM ${S}.REG_REPORTING_SUMMARY GROUP BY 1 ORDER BY 1`),
      q(`SELECT REJECT_REASON, ENTITY, COUNT(*) AS N FROM ${S}.REG_TRANSACTION_REPORTS
         WHERE STATUS = 'REJECTED' GROUP BY ALL ORDER BY N DESC LIMIT 20`),
      q(`SELECT ENTITY, COUNT(*) AS DAYS, COUNT_IF(RECON_STATUS = 'SHORTFALL') AS SHORTFALL_DAYS,
                MIN(DIFFERENCE_GBP) AS WORST_DIFFERENCE,
                MAX_BY(RECON_STATUS, RECON_DATE) AS LATEST_STATUS, MAX_BY(DIFFERENCE_GBP, RECON_DATE) AS LATEST_DIFFERENCE
         FROM ${S}.CLIENT_MONEY_RECON_V GROUP BY 1 ORDER BY SHORTFALL_DAYS DESC`),
      q(`SELECT ENTITY, PRIMARY_PRODUCT, SUM(CLIENTS) AS CLIENTS, AVG(PCT_LOSING_CLIENTS) AS PCT_LOSING,
                AVG(COMPLAINTS_PER_1000) AS COMPLAINTS_PER_1000, AVG(AVG_NPS) AS NPS
         FROM ${S}.CONSUMER_DUTY_OUTCOMES WHERE SEGMENT = 'Retail' GROUP BY ALL ORDER BY PCT_LOSING DESC NULLS LAST LIMIT 20`),
      q(`SELECT COUNT(*) AS REPORTS, 100 * COUNT_IF(STATUS = 'ACCEPTED') / COUNT(*) AS ACCEPTANCE_PCT,
                COUNT_IF(STATUS = 'REJECTED') AS REJECTED, COUNT_IF(STATUS = 'LATE') AS LATE,
                (SELECT COUNT_IF(RECON_STATUS = 'SHORTFALL') FROM ${S}.CLIENT_MONEY_RECON_V
                  WHERE RECON_DATE >= DATEADD(day, -30, CURRENT_DATE())) AS CASS_BREAKS_30D
         FROM ${S}.REG_TRANSACTION_REPORTS`),
    ]);
    return Response.json({ byEntity, daily, rejects, cass, duty, kpi: kpi[0] ?? {} });
  } catch (e) {
    return errorResponse('compliance', e);
  }
}
